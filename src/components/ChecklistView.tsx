import React, { useState } from 'react';
import {
  CheckSquare,
  Plus,
  Trash2,
  Calendar,
  Layers,
  CheckCircle2,
  BookmarkCheck,
  AlertCircle,
  X,
} from 'lucide-react';
import { UserTask } from '../types/tcas';
import {
  EnrichedAdmissionProject,
  formatDateThai,
  getUniversityThaiAbbr,
} from '../utils/tcasHelpers';

interface ChecklistViewProps {
  tasks: UserTask[];
  trackedProjects: EnrichedAdmissionProject[];
  onToggleTask: (taskId: string) => void;
  onAddTask: (newTask: Omit<UserTask, 'id' | 'isCompleted'>) => void;
  onDeleteTask: (taskId: string) => void;
  onOpenDetail: (project: EnrichedAdmissionProject) => void;
}

export const ChecklistView: React.FC<ChecklistViewProps> = ({
  tasks,
  trackedProjects,
  onToggleTask,
  onAddTask,
  onDeleteTask,
  onOpenDetail,
}) => {
  const [filterProjectId, setFilterProjectId] = useState<string>('all');
  const [showAddModal, setShowAddModal] = useState<boolean>(false);

  // New task form state
  const [newTitle, setNewTitle] = useState('');
  const [newDueDate, setNewDueDate] = useState('2026-11-13');
  const [newProjectId, setNewProjectId] = useState(
    trackedProjects[0]?.project.id || ''
  );
  const [newCategory, setNewCategory] = useState<UserTask['category']>('document');

  const filteredTasks = tasks.filter((t) => {
    if (filterProjectId !== 'all' && t.projectId !== filterProjectId) {
      return false;
    }
    return true;
  });

  const totalTasks = tasks.length;
  const completedTasks = tasks.filter((t) => t.isCompleted).length;
  const progressPercent = totalTasks > 0 ? Math.round((completedTasks / totalTasks) * 100) : 0;

  const handleCreateTask = (e: React.FormEvent) => {
    e.preventDefault();
    if (!newTitle.trim()) return;

    onAddTask({
      titleEn: newTitle.trim(),
      titleTh: newTitle.trim(),
      dueDate: newDueDate || undefined,
      projectId: newProjectId || undefined,
      category: newCategory,
      isAutoGenerated: false,
    });

    setNewTitle('');
    setShowAddModal(false);
  };

  const getCategoryThai = (cat: string) => {
    switch (cat) {
      case 'document': return 'เตรียมเอกสาร';
      case 'submission': return 'ยื่นใบสมัคร';
      case 'payment': return 'ชำระค่าสมัคร';
      case 'interview': return 'สอบสัมภาษณ์';
      default: return 'ทั่วไป';
    }
  };

  return (
    <div className="space-y-6">
      {/* Title & Action Bar in Thai */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-slate-200 pb-5">
        <div>
          <h1 className="text-xl sm:text-2xl font-bold tracking-tight text-slate-900">
            เช็กลิสต์สิ่งที่ต้องทำสำหรับการสมัคร TCAS
          </h1>
          <p className="text-xs sm:text-sm text-slate-500 mt-0.5">
            สร้างเช็กลิสต์เตรียมเอกสารอัตโนมัติจากระเบียบการ และเพิ่มสิ่งที่ต้องทำด้วยตนเอง
          </p>
        </div>

        <button
          onClick={() => setShowAddModal(true)}
          className="inline-flex items-center gap-1.5 px-4 py-2 text-xs font-bold rounded-xl bg-blue-600 hover:bg-blue-700 text-white transition-all shadow-sm cursor-pointer"
        >
          <Plus className="h-4 w-4" />
          <span>+ เพิ่มสิ่งที่ต้องทำ</span>
        </button>
      </div>

      {/* Overall Progress Bar */}
      <div className="bg-white border border-slate-200/90 rounded-2xl p-5 shadow-xs space-y-3">
        <div className="flex items-center justify-between text-xs">
          <span className="font-bold text-slate-800">
            ความคืบหน้าการเตรียมตัวและการยื่นสมัครทั้งหมด
          </span>
          <span className="font-mono font-bold text-blue-700 tabular-nums text-sm">
            เสร็จสิ้น {completedTasks} / {totalTasks} รายการ ({progressPercent}%)
          </span>
        </div>
        <div className="h-2.5 w-full bg-slate-100 rounded-full overflow-hidden">
          <div
            className="h-full bg-blue-600 rounded-full transition-all duration-300"
            style={{ width: `${progressPercent}%` }}
          />
        </div>
      </div>

      {/* Program Filter Pills */}
      <div className="flex items-center gap-2 overflow-x-auto pb-1 text-xs scrollbar-none">
        <button
          onClick={() => setFilterProjectId('all')}
          className={`px-3.5 py-1.5 rounded-xl font-bold whitespace-nowrap transition-all cursor-pointer ${
            filterProjectId === 'all'
              ? 'bg-slate-900 text-white shadow-xs'
              : 'bg-white border border-slate-200 text-slate-700 hover:bg-slate-50'
          }`}
        >
          งานทั้งหมด ({tasks.length})
        </button>

        {trackedProjects.map((p) => {
          const pTasks = tasks.filter((t) => t.projectId === p.project.id);
          const pDone = pTasks.filter((t) => t.isCompleted).length;
          const uniTh = getUniversityThaiAbbr(p.university.id);

          return (
            <button
              key={p.project.id}
              onClick={() => setFilterProjectId(p.project.id)}
              className={`px-3.5 py-1.5 rounded-xl font-bold whitespace-nowrap transition-all cursor-pointer flex items-center gap-1.5 ${
                filterProjectId === p.project.id
                  ? 'bg-blue-600 text-white shadow-xs'
                  : 'bg-white border border-slate-200 text-slate-700 hover:bg-slate-50'
              }`}
            >
              <span>{uniTh} — {p.program.nameTh}</span>
              <span className="font-mono text-[11px] opacity-80 tabular-nums">
                ({pDone}/{pTasks.length})
              </span>
            </button>
          );
        })}
      </div>

      {/* Task List */}
      {filteredTasks.length === 0 ? (
        <div className="p-12 text-center bg-white border border-slate-200 rounded-2xl space-y-3">
          <CheckSquare className="h-8 w-8 text-slate-400 mx-auto" />
          <h3 className="text-sm font-semibold text-slate-800">ไม่มีรายการสิ่งที่ต้องทำในหมวดหมู่นี้</h3>
          <p className="text-xs text-slate-500">
            บันทึกสาขาเพิ่มเติม หรือกดปุ่ม "เพิ่มสิ่งที่ต้องทำ" เพื่อสร้างรายการเตือนความจำ
          </p>
        </div>
      ) : (
        <div className="bg-white border border-slate-200/90 rounded-2xl divide-y divide-slate-100 overflow-hidden shadow-xs">
          {filteredTasks.map((task) => {
            const project = trackedProjects.find((p) => p.project.id === task.projectId);
            const uniTh = project ? getUniversityThaiAbbr(project.university.id) : '';

            return (
              <div
                key={task.id}
                className={`p-4 flex items-start justify-between gap-4 transition-colors ${
                  task.isCompleted ? 'bg-slate-50/50' : 'hover:bg-slate-50/70'
                }`}
              >
                <div className="flex items-start gap-3">
                  <button
                    onClick={() => onToggleTask(task.id)}
                    className={`h-5 w-5 mt-0.5 rounded-md border flex items-center justify-center shrink-0 transition-colors cursor-pointer ${
                      task.isCompleted
                        ? 'bg-emerald-600 border-emerald-600 text-white'
                        : 'border-slate-300 hover:border-slate-500 bg-white'
                    }`}
                  >
                    {task.isCompleted && <span className="text-xs font-bold">✓</span>}
                  </button>

                  <div className="space-y-1">
                    <div
                      onClick={() => onToggleTask(task.id)}
                      className={`text-sm font-semibold leading-snug cursor-pointer ${
                        task.isCompleted ? 'line-through text-slate-400' : 'text-slate-900'
                      }`}
                    >
                      {task.titleTh || task.titleEn}
                    </div>

                    <div className="flex flex-wrap items-center gap-2 text-xs text-slate-500">
                      {project && (
                        <button
                          onClick={() => onOpenDetail(project)}
                          className="font-bold text-blue-600 hover:text-blue-800 underline"
                        >
                          {uniTh} · {project.program.nameTh}
                        </button>
                      )}
                      {task.dueDate && (
                        <>
                          <span className="text-slate-300">·</span>
                          <span className="font-semibold text-slate-700">
                            กำหนดส่ง {formatDateThai(task.dueDate)}
                          </span>
                        </>
                      )}
                      <span className="text-slate-300">·</span>
                      <span className="px-2 py-0.2 rounded-md bg-slate-100 text-slate-700 text-[11px] font-medium">
                        {getCategoryThai(task.category)}
                      </span>
                      {task.isAutoGenerated && (
                        <span className="text-[10px] bg-blue-50 text-blue-700 px-1.5 py-0.2 rounded font-semibold border border-blue-100">
                          สร้างอัตโนมัติจากระเบียบการ
                        </span>
                      )}
                    </div>
                  </div>
                </div>

                <button
                  onClick={() => onDeleteTask(task.id)}
                  className="text-slate-400 hover:text-rose-600 p-1.5 rounded-lg hover:bg-rose-50 transition-colors cursor-pointer"
                  title="ลบรายการนี้"
                >
                  <Trash2 className="h-4 w-4" />
                </button>
              </div>
            );
          })}
        </div>
      )}

      {/* Add Task Modal in Thai */}
      {showAddModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-xs">
          <div className="w-full max-w-md bg-white rounded-2xl shadow-xl border border-slate-200 p-6 space-y-4">
            <div className="flex items-center justify-between pb-2 border-b border-slate-100">
              <h3 className="text-base font-bold text-slate-900">เพิ่มสิ่งที่ต้องทำด้วยตนเอง</h3>
              <button
                onClick={() => setShowAddModal(false)}
                className="p-1 text-slate-400 hover:text-slate-700 rounded-lg"
              >
                <X className="h-5 w-5" />
              </button>
            </div>

            <form onSubmit={handleCreateTask} className="space-y-3.5 text-xs">
              <div className="space-y-1">
                <label className="font-bold text-slate-700">ชื่อรายการสิ่งที่ต้องทำ</label>
                <input
                  type="text"
                  required
                  value={newTitle}
                  onChange={(e) => setNewTitle(e.target.value)}
                  placeholder="เช่น ขอใบ ปพ.1 จากห้องทะเบียนโรงเรียน, ตรวจไฟล์ PDF พอร์ตโฟลิโอ"
                  className="w-full p-2.5 border border-slate-300 rounded-xl text-sm text-slate-900 focus:outline-none focus:ring-2 focus:ring-blue-500 font-medium"
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div className="space-y-1">
                  <label className="font-bold text-slate-700">กำหนดส่ง / เดดไลน์</label>
                  <input
                    type="date"
                    value={newDueDate}
                    onChange={(e) => setNewDueDate(e.target.value)}
                    className="w-full p-2 border border-slate-300 rounded-xl text-xs text-slate-900"
                  />
                </div>

                <div className="space-y-1">
                  <label className="font-bold text-slate-700">หมวดหมู่</label>
                  <select
                    value={newCategory}
                    onChange={(e) => setNewCategory(e.target.value as UserTask['category'])}
                    className="w-full p-2 border border-slate-300 rounded-xl text-xs text-slate-900"
                  >
                    <option value="document">เตรียมเอกสาร</option>
                    <option value="submission">ยื่นใบสมัคร</option>
                    <option value="payment">ชำระค่าสมัคร</option>
                    <option value="interview">สอบสัมภาษณ์</option>
                    <option value="other">อื่นๆ</option>
                  </select>
                </div>
              </div>

              {trackedProjects.length > 0 && (
                <div className="space-y-1">
                  <label className="font-bold text-slate-700">สาขาที่เกี่ยวข้อง</label>
                  <select
                    value={newProjectId}
                    onChange={(e) => setNewProjectId(e.target.value)}
                    className="w-full p-2 border border-slate-300 rounded-xl text-xs text-slate-900"
                  >
                    {trackedProjects.map((p) => (
                      <option key={p.project.id} value={p.project.id}>
                        {getUniversityThaiAbbr(p.university.id)} — {p.program.nameTh}
                      </option>
                    ))}
                  </select>
                </div>
              )}

              <div className="pt-2 flex justify-end gap-2">
                <button
                  type="button"
                  onClick={() => setShowAddModal(false)}
                  className="px-4 py-2 border border-slate-200 rounded-xl text-slate-700 font-bold hover:bg-slate-50 cursor-pointer"
                >
                  ยกเลิก
                </button>
                <button
                  type="submit"
                  className="px-4 py-2 bg-blue-600 hover:bg-blue-700 text-white rounded-xl font-bold transition-all shadow-xs cursor-pointer"
                >
                  บันทึกรายการ
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
};
